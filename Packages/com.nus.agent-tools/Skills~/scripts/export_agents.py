"""Copy the toolkit's skills into a project so coding agents other than Claude Code can use them.

    python export_agents.py                         # .github/skills/<skill>/ and a section in AGENTS.md
    python export_agents.py --targets agents        # .agents/skills/<skill>/ instead
    python export_agents.py --check                 # exit 1 if the copies are missing or out of date
    python export_agents.py --off                   # remove the copies and the AGENTS.md section

Claude Code users get the skills from the nus-unity-toolkit plugin. Other agents read skills from the repository:
GitHub Copilot from .github/skills/, some tools from .agents/skills/, and Codex, Cursor, Gemini CLI and others from
AGENTS.md. This script writes those copies, with `${CLAUDE_SKILL_DIR}` replaced by the copy's path from the repository
root, and lists every skill in a marked section of AGENTS.md. Commit what it writes, and run it again after each
toolkit update.

It runs from the toolkit repository, the Claude Code plugin, or the Unity package in a project's
Library/PackageCache/com.nus.agent-tools@*/Skills~/scripts/. The project is the git repository of the working
directory unless --project says otherwise. A skill folder it didn't write is never overwritten or removed.
"""

import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
SKILLS = HERE.parent / "skills"
PLUGIN_JSON = HERE.parent / ".claude-plugin" / "plugin.json"
SKILL_DIRS = {"github": ".github/skills", "agents": ".agents/skills"}
TARGETS = ["github", "agents", "agents-md"]
DEFAULT_TARGETS = ["github", "agents-md"]
STAMP = ".nus-unity-toolkit.json"
GENERATED_MARK = "<!-- Generated by nus-unity-toolkit"
AGENTS_MD_BLOCK = re.compile(r"\n*<!-- nus-unity-toolkit:start -->.*?<!-- nus-unity-toolkit:end -->\n?", re.S)
SKIP_DIRS = {"__pycache__", ".pytest_cache"}
NEEDS_BRIDGE = "Unity_RunCommand"


def fail(message, detail=""):
    """Exit with a first line a person can act on; the detail follows."""
    sys.exit(f"{message}\n{detail}".rstrip())


def toolkit_version():
    try:
        return json.loads(PLUGIN_JSON.read_text(encoding="utf-8-sig"))["version"]
    except (OSError, ValueError, KeyError):
        return "unknown"


def project_root(given):
    if given:
        root = pathlib.Path(given).resolve()
        if not root.is_dir():
            fail(f"There is no folder at {root}.")
        return root
    proc = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    if proc.returncode != 0:
        fail("Run this inside the project's git repository, or pass --project <folder>.")
    return pathlib.Path(proc.stdout.strip()).resolve()


# --- the skills as they are shipped ------------------------------------------------

def frontmatter(text):
    """The name and description from a SKILL.md's leading --- block."""
    m = re.match(r"---\r?\n(.*?)\r?\n---\r?\n", text, re.S)
    if not m:
        return {}
    fields = {}
    for line in m.group(1).splitlines():
        key, sep, value = line.partition(":")
        if sep:
            fields[key.strip()] = value.strip()
    return fields


def shipped_skills():
    """{name: {"dir", "description", "bridge"}} for every skill folder holding a SKILL.md, by name."""
    skills = {}
    for folder in sorted(p for p in SKILLS.iterdir() if (p / "SKILL.md").is_file()):
        text = (folder / "SKILL.md").read_text(encoding="utf-8-sig")
        meta = frontmatter(text)
        skills[meta.get("name") or folder.name] = {"dir": folder, "description": meta.get("description", ""),
                                                   "bridge": NEEDS_BRIDGE in text}
    return skills


def shipped_files(folder):
    """The files a copy needs: everything but caches and the skill's own tests."""
    for path in sorted(folder.rglob("*")):
        rel = path.relative_to(folder)
        if path.is_file() and not SKIP_DIRS.intersection(rel.parts) and path.suffix != ".pyc" \
                and not path.name.startswith("test_"):
            yield rel


def portable_skill(text, skill_path, version, bridge):
    """The SKILL.md for other agents: script paths from the repository root, and a note saying where it came from."""
    text = text.replace("${CLAUDE_SKILL_DIR}", skill_path)
    newline = "\r\n" if "\r\n" in text else "\n"
    note = (f"{GENERATED_MARK} {version}. Don't edit: run export_agents.py again after a toolkit update. "
            f"Paths are from the repository root. -->{newline}")
    if bridge:
        note += (f"{newline}> **Needs the Unity MCP bridge** (the Unity AI Assistant's MCP server) for the steps that "
                 f"call `{NEEDS_BRIDGE}`. Without it, do the steps that need no editor and say which you couldn't "
                 f"check.{newline}")
    m = re.match(r"---\r?\n.*?\r?\n---\r?\n", text, re.S)
    end = m.end() if m else 0
    return text[:end] + newline + note + text[end:]


def normalised(data):
    """Text with LF line endings, so a copy matches however git checked either side out; other bytes as they are."""
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        return data
    return data.replace(b"\r\n", b"\n")


def expected_copy(name, skill, base, version):
    """{relative path: bytes} of one skill's copy under base (e.g. .github/skills)."""
    files = {}
    skill_path = f"{base}/{name}"
    for rel in shipped_files(skill["dir"]):
        data = (skill["dir"] / rel).read_bytes()
        if rel.as_posix() == "SKILL.md":
            data = portable_skill(data.decode("utf-8-sig"), skill_path, version, skill["bridge"]).encode("utf-8")
        files[rel.as_posix()] = normalised(data)
    return files


def agents_md_section(skills, base, version):
    rows = "\n".join(
        f"| `{name}` | {s['description'].replace('|', '/')} | `{base}/{name}/SKILL.md` | {'yes' if s['bridge'] else ''} |"
        for name, s in skills.items())
    return ("<!-- nus-unity-toolkit:start -->\n"
            f"## Unity toolkit skills (nus-unity-toolkit {version})\n\n"
            "Each skill is a folder of instructions (`SKILL.md`) and scripts. When a task matches a skill's use, read "
            "its `SKILL.md` and follow it; run its scripts from the repository root. Skills marked *Unity bridge* "
            "need the Unity AI Assistant's MCP server for some steps. Generated by `export_agents.py`; don't edit "
            "this section, run the export again after a toolkit update.\n\n"
            "| Skill | Use it | Instructions | Unity bridge |\n|---|---|---|---|\n"
            f"{rows}\n"
            "<!-- nus-unity-toolkit:end -->\n")


# --- the project's copies ----------------------------------------------------------

def read_stamp(root, base):
    path = root / base / STAMP
    try:
        return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}
    except ValueError:
        return {}


def ours(root, base, name, stamp):
    """True if the folder base/name was written by this script (listed in its stamp, or its SKILL.md says so)."""
    skill_md = root / base / name / "SKILL.md"
    if name in stamp.get("skills", []):
        return True
    return skill_md.is_file() and GENERATED_MARK in skill_md.read_text(encoding="utf-8-sig", errors="replace")


def plan(root, targets, skills, version):
    """What has to change: [(action, relative path)] with action 'write', 'remove' or 'skip'; and the new contents."""
    changes, contents = [], {}
    for target in targets:
        if target == "agents-md":
            continue
        base = SKILL_DIRS[target]
        stamp = read_stamp(root, base)
        for name, skill in skills.items():
            folder = root / base / name
            if folder.exists() and not ours(root, base, name, stamp):
                changes.append(("skip", f"{base}/{name}"))
                continue
            want = expected_copy(name, skill, base, version)
            have = {p.relative_to(folder).as_posix() for p in folder.rglob("*") if p.is_file()} if folder.exists() else set()
            for rel, data in want.items():
                path = folder / rel
                if not path.is_file() or normalised(path.read_bytes()) != data:
                    changes.append(("write", f"{base}/{name}/{rel}"))
                    contents[f"{base}/{name}/{rel}"] = data
            for rel in sorted(have - set(want)):
                changes.append(("remove", f"{base}/{name}/{rel}"))
        for name in stamp.get("skills", []):
            if name not in skills and (root / base / name).exists():
                changes.append(("remove", f"{base}/{name}"))
        stamp_data = (json.dumps({"toolkit": version, "skills": sorted(n for n in skills
                                  if ("skip", f"{base}/{n}") not in changes)}, indent=2) + "\n").encode("utf-8")
        stamp_path = root / base / STAMP
        if not stamp_path.is_file() or normalised(stamp_path.read_bytes()) != stamp_data:
            changes.append(("write", f"{base}/{STAMP}"))
            contents[f"{base}/{STAMP}"] = stamp_data
    if "agents-md" in targets:
        base = next((SKILL_DIRS[t] for t in targets if t in SKILL_DIRS), None)
        if base is None:
            fail("agents-md lists the skills' copies, so give github or agents as well.")
        listed = {n: s for n, s in skills.items() if ("skip", f"{base}/{n}") not in changes}
        path = root / "AGENTS.md"
        current = path.read_text(encoding="utf-8-sig").replace("\r\n", "\n") if path.is_file() else ""
        body = AGENTS_MD_BLOCK.sub("\n\n", current).rstrip("\n")
        new = ((body + "\n\n") if body else "") + agents_md_section(listed, base, version)
        if new != current:
            changes.append(("write", "AGENTS.md"))
            contents["AGENTS.md"] = new.encode("utf-8")
    return changes, contents


def apply(root, changes, contents):
    for action, rel in changes:
        path = root / rel
        if action == "write":
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents[rel])
        elif action == "remove":
            shutil.rmtree(path) if path.is_dir() else path.unlink()


def remove_all(root, targets):
    removed = []
    for target in targets:
        if target == "agents-md":
            path = root / "AGENTS.md"
            if path.is_file():
                text = path.read_text(encoding="utf-8-sig")
                body = AGENTS_MD_BLOCK.sub("\n\n", text).strip("\n")
                if body != text.strip("\n"):
                    path.write_text(body + "\n", encoding="utf-8") if body else path.unlink()
                    removed.append("AGENTS.md section")
            continue
        base = SKILL_DIRS[target]
        stamp = read_stamp(root, base)
        for folder in sorted((root / base).glob("*")) if (root / base).is_dir() else []:
            if folder.is_dir() and ours(root, base, folder.name, stamp):
                shutil.rmtree(folder)
                removed.append(f"{base}/{folder.name}")
        if (root / base / STAMP).is_file():
            (root / base / STAMP).unlink()
    return removed


def main(argv=None):
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--project", help="The project's root folder. Defaults to the git repository you are in.")
    parser.add_argument("--targets", nargs="+", choices=TARGETS,
                        help=f"Where to write: {', '.join(TARGETS)}. Default: {' '.join(DEFAULT_TARGETS)}.")
    parser.add_argument("--check", action="store_true", help="Change nothing; exit 1 if the copies are out of date.")
    parser.add_argument("--off", action="store_true", help="Remove the copies and the AGENTS.md section this wrote.")
    args = parser.parse_args(argv)

    root = project_root(args.project)
    targets = args.targets or DEFAULT_TARGETS
    if args.off:
        print(json.dumps({"project": str(root), "removed": remove_all(root, targets)}, ensure_ascii=False))
        return 0
    version = toolkit_version()
    skills = shipped_skills()
    changes, contents = plan(root, targets, skills, version)
    pending = [{"action": a, "path": p} for a, p in changes if a != "skip"]
    skipped = [p for a, p in changes if a == "skip"]
    if not args.check:
        apply(root, changes, contents)
    print(json.dumps({"project": str(root), "toolkit": version, "skills": list(skills),
                      ("outOfDate" if args.check else "changed"): pending,
                      "leftAlone": skipped}, ensure_ascii=False))
    if skipped:
        print(f"Left alone (not written by this script): {', '.join(skipped)}", file=sys.stderr)
    return 1 if args.check and pending else 0


if __name__ == "__main__":
    sys.exit(main())
